rest_lines.append('')
rest_lines.append('')
rest_lines.append("if name == 'main':")
rest_lines.append(TB + 'loop_forever()')
rest_lines.append('')

out = head + NL.join(rest_lines)
open(p, 'w', encoding='utf-8', newline='').write(out)
print('APPENDED')
try:
 ast.parse(out)
 print('AST OK')
except SyntaxError as e:
 print('AST ERR line', e.lineno, ':', e.msg)
